  LmodMessage("    what your agents do.") 
  LmodMessage("")
  LmodMessage("USAGE:")
  LmodMessage("")
  LmodMessage("After obtaining llm-gateway or Aalto Azure keys run:")
  LmodMessage("")
  LmodMessage("    moat-install")
  LmodMessage("")
  LmodMessage("This will create a fake home directory for the agents in $WRKDIR/agents-home")
  LmodMessage("and it will configure the harnesses' so that they use Aalto provided LLMs.")
  LmodMessage("You can of course configure your own providers as well.")
  LmodMessage("")
  LmodMessage("To start an interactive terminal in the container")
  LmodMessage("(fake home directory $WRKDIR/agents-home")
  LmodMessage("and the current directory are available in the container):")
  LmodMessage("")
  LmodMessage("    moat run -n agents bash")
  LmodMessage("")
  LmodMessage("To run an agent (e.g. codex/claude/pi/opencode/cline/omp/goose) in the container")
  LmodMessage("(agent configurations will be stored in fake home directory $WKRDIR/agents-home")
